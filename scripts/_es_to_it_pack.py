PHRASES.sort(key=lambda pair: len(pair[0]), reverse=True)
DASH_RE = re.compile(r"[—–]")


def convert(text: str) -> str:
    text = DASH_RE.sub(", ", text)
    for src, dst in PHRASES:
        text = text.replace(src, dst)
    # glossary: never translate product terms that slipped through
    text = re.sub(r"\bcollega\b", "coworker", text, flags=re.I)
    text = re.sub(r"\bcolleghi\b", "coworker", text, flags=re.I)
    return text


def walk(obj):
    if isinstance(obj, dict):
        return {k: walk(v) for k, v in obj.items() if k != "_context"}
    if isinstance(obj, str):
        return convert(obj)
    return obj


def main() -> None:
    for name in FILES:
        es_path = ROOT / "es" / f"{name}.json"
        tree = json.loads(es_path.read_text(encoding="utf-8"))
        it_tree = walk(tree)
        out = ROOT / "it" / f"{name}.json"
        out.write_text(json.dumps(it_tree, indent=4, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {out}")


if __name__ == "__main__":
    main()